#!/usr/bin/env python3
"""Builds resources/AppIcon.svg from the pi mark: the mark, with its own
colors and effects, on a dark macOS plate (824 px body, 100 px margin) with
the template shadow and lighting.

The mark SVG is embedded as a nested <svg>. If it defines a `tile` path (the
plate the mark was designed on), the mark is scaled so that tile matches our
plate; otherwise its whole viewBox is fitted to the plate.

Usage: script/icon_from_mark.py path/to/pi-mark.svg
"""
import re
import sys
from pathlib import Path

PLATE = (100.0, 924.0)

mark = Path(sys.argv[1]).read_text()
view_box = re.search(r'viewBox="([^"]+)"', mark)
vx, vy, vw, vh = (float(n) for n in view_box.group(1).split()) if view_box else (0, 0, 1024, 1024)

tile = re.search(r'<path id="tile" d="([^"]+)"', mark)
if tile:
    numbers = [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", tile.group(1))]
    low, high = min(numbers), max(numbers)
else:
    low, high = vx, vx + vw
scale = (PLATE[1] - PLATE[0]) / (high - low)
offset = PLATE[0] - (low - vx) * scale
size = vw * scale

inner = re.search(r"<svg[^>]*>(.*)</svg>", mark, re.S).group(1)
inner = re.sub(r"<title>.*?</title>", "", inner, flags=re.S)

svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <title>Pi GPUI</title>
  <desc>Generated by script/icon_from_mark.py from the pi mark.</desc>
  <defs>
    <linearGradient id="app-plate" x1="0" y1="100" x2="0" y2="924" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#1b222b"/>
      <stop offset="0.32" stop-color="#080d12"/>
      <stop offset="0.67" stop-color="#0c1117"/>
      <stop offset="1" stop-color="#05090d"/>
    </linearGradient>
    <radialGradient id="app-sheen" cx="470" cy="40" r="640" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#d6e1f2" stop-opacity="0.22"/>
      <stop offset="0.5" stop-color="#a7b5c9" stop-opacity="0.04"/>
      <stop offset="1" stop-color="#8a9aad" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="app-rim" x1="0.18" y1="0" x2="0.75" y2="1">
      <stop offset="0" stop-color="#e5eaf2" stop-opacity="0.55"/>
      <stop offset="0.2" stop-color="#83909f" stop-opacity="0.18"/>
      <stop offset="0.5" stop-color="#7c8a99" stop-opacity="0.06"/>
      <stop offset="0.8" stop-color="#b8c7d7" stop-opacity="0.14"/>
      <stop offset="1" stop-color="#637180" stop-opacity="0.14"/>
    </linearGradient>
    <filter id="app-plate-shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur stdDeviation="14"/>
    </filter>
    <clipPath id="app-plate-clip">
      <rect x="100" y="100" width="824" height="824" rx="185"/>
    </clipPath>
  </defs>

  <rect x="100" y="112" width="824" height="824" rx="185" fill="#000000" opacity="0.45" filter="url(#app-plate-shadow)"/>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#app-plate)"/>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#app-sheen)"/>

  <g clip-path="url(#app-plate-clip)">
    <svg x="{offset:.2f}" y="{offset:.2f}" width="{size:.2f}" height="{size * vh / vw:.2f}" viewBox="{vx:g} {vy:g} {vw:g} {vh:g}" overflow="visible">
{inner}
    </svg>
  </g>

  <rect x="101.5" y="101.5" width="821" height="821" rx="183.5" fill="none" stroke="url(#app-rim)" stroke-width="3"/>
</svg>
"""
Path("resources/AppIcon.svg").write_text(svg)
print("resources/AppIcon.svg")
